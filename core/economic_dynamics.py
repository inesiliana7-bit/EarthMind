class EconomicDynamics:

    def next_year(self, state):

        s = state.copy()

        # ==================================================
        # 1. GDP
        # ==================================================

        gdp_effect = (

            (s["investment"] - 50) * 0.035

            +

            (s["employment"] - 50) * 0.025

            -

            (s["inflation"] - 50) * 0.020

        )

        s["gdp"] += gdp_effect


        # ==================================================
        # 2. Employment
        # ==================================================

        employment_effect = (

            (s["gdp"] - 50) * 0.020

            +

            (s["investment"] - 50) * 0.010

        )

        s["employment"] += employment_effect


        # ==================================================
        # 3. Investment
        # ==================================================

        investment_effect = (

            (s["gdp"] - 50) * 0.025

            +

            (s["employment"] - 50) * 0.010

        )

        s["investment"] += investment_effect


        # ==================================================
        # 4. Inflation
        # ==================================================

        inflation_effect = (

            -(s["investment"] - 50) * 0.012

            -(s["employment"] - 50) * 0.008

            +(50 - s["gdp"]) * 0.010

        )

        s["inflation"] += inflation_effect


        # ==================================================
        # 5. Poverty
        # ==================================================

        poverty_effect = (

            -(s["employment"] - 50) * 0.025

            -(s["gdp"] - 50) * 0.015

        )

        s["poverty"] += poverty_effect


        # ==================================================
        # 6. Quality of Life
        # ==================================================

        s["life"] = (

            s["health"] * 0.30

            +

            s["education"] * 0.25

            +

            s["gdp"] * 0.20

            +

            s["housing"] * 0.15

            +

            s["air"] * 0.10

        )


        # ==================================================
        # 7. Safety bounds
        # ==================================================

        for key in s:

            s[key] = max(
                0,
                min(
                    s[key],
                    100
                )
            )

        return s